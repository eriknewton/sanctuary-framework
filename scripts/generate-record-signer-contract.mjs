import { readFileSync, writeFileSync } from "node:fs";
import { tsImport } from "../server/node_modules/tsx/dist/esm/api/index.mjs";
const root = new URL("../", import.meta.url);
// Must match the entire evaluated registry in server/src/signing/contract.ts.
const contract = await tsImport(new URL("server/src/signing/contract.ts", root).href, import.meta.url);
const quote = value => JSON.stringify(value);
let output = "// Generated by scripts/generate-record-signer-contract.mjs; do not hand edit.\n";
output += "// Must match server/src/signing/contract.ts, which owns all roles, kinds, fields and primitive constants.\n";
output += "pub const ROLE_REGISTRY: &[(&str, &str, usize)] = &[\n";
output += contract.ROLE_REGISTRY.map(row => `    (${quote(row.role)}, ${quote(row.domain)}, ${row.envelope_max_bytes}),`).join("\n") + "\n];\n";
output += "pub const RECORD_KINDS: &[(&str, &[&str])] = &[\n";
output += contract.ROLE_REGISTRY.map(row => `    (${quote(row.role)}, &[${row.record_kinds.map(quote).join(", ")}]),`).join("\n") + "\n];\n";
for (const [name, value] of Object.entries(contract)) {
  if (typeof value !== "string" && typeof value !== "number") continue;
  output += `pub const ${name}: ${typeof value === "string" ? '&str' : 'usize'} = ${quote(value)};\n`;
}
for (const name of ["COMMON_FIELDS", "LINUX_FIELDS"]) {
  output += `pub const ${name}: &[&str] = &[${contract[name].map(quote).join(", ")}];\n`;
}
function emit(name, bytes) {
  const target = new URL(`castle-wall-daemon/src/business_profile/${name}`, root);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== bytes) throw new Error(`K1 generated ${name} differs`);
  } else writeFileSync(target, bytes);
}
emit("signer_contract.rs", output);
// Must match every public vector in server/test/signing/strict-verifier.test.ts without importing its test runner.
const source = readFileSync(new URL("server/test/signing/strict-verifier.test.ts", root), "utf8");
for (const name of ["PUBLIC_VECTORS", "ROLE_VECTORS"]) {
  const values = JSON.parse(source.split(`// ${name}_BEGIN\nexport const ${name} = `)[1].split(`;\n// ${name}_END`)[0]);
  emit(name.toLowerCase() + ".json", JSON.stringify(values, null, 2) + "\n");
}
