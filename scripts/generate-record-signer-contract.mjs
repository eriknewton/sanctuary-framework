import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const source = readFileSync(new URL("server/src/signing/contract.ts", root), "utf8");
const roles = JSON.parse(source.match(/export const ROLE_REGISTRY = ([\s\S]*?) as const;/)[1]);
const quote = value => JSON.stringify(value);
let output = "// Generated by scripts/generate-record-signer-contract.mjs; do not hand edit.\n";
output += "// Contract pin: server/src/signing/contract.ts owns the complete role, schema and constant sets.\n";
output += "pub const ROLE_REGISTRY: &[(&str, &str, usize)] = &[\n";
output += roles.map(row => `    (${quote(row.role)}, ${quote(row.domain)}, ${row.envelope_max_bytes}),`).join("\n") + "\n];\n";
for (const [, name, value] of source.matchAll(/export const ([A-Z][A-Z_0-9]+) = ("(?:[^"\\]|\\.)*"|\d+);/g)) {
  output += `pub const ${name}: ${value.startsWith('"') ? '&str' : 'usize'} = ${value};\n`;
}
for (const name of ["COMMON_FIELDS", "LINUX_FIELDS"]) {
  const values = JSON.parse(source.match(new RegExp(`export const ${name} = (\\[[^;]+\\]) as const;`))[1]);
  output += `pub const ${name}: &[&str] = &[${values.map(quote).join(", ")}];\n`;
}
const target = fileURLToPath(new URL("castle-wall-daemon/src/business_profile/signer_contract.rs", root));
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("K1 generated contract differs");
} else writeFileSync(target, output);
