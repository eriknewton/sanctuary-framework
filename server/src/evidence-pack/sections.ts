// ── Section 10: verification instructions ────────────────────────────

function renderVerification(signerDid: string): PackSection {
  const body = [
    "# Verifying this pack as a third party",
    "",
    "_For an underwriter or a client's auditor who does not trust the vendor._",
    "",
    "Each Markdown file in this pack is individually SHA-256 hashed and " +
      "Ed25519-signed with the firm's primary identity; the signatures and " +
      "hashes are recorded in `00_pack_manifest.json`. To verify a file " +
      "without any Sanctuary software:",
    "",
    "1. Recompute the file's SHA-256 (for example, `sha256sum <file>`) and " +
      "confirm it matches the `sha256` recorded for that file in the manifest.",
    "2. Verify the Ed25519 signature over that SHA-256 digest against the " +
      `signer public key in the manifest (signer: ${signerDid}).`,
    "3. Verify the manifest's own `manifest_signature` over its canonical body.",
    "",
    "IMPORTANT: the rendered PDF is a human-readable copy and is NOT itself " +
      "cryptographically signed (this is deliberate). Integrity lives in the " +
      "signed Markdown files and the manifest, not in the PDF.",
    "",
    "Where the discrete evidence exports are included alongside this pack " +
      "(the signed transparency checkpoint bundle, any public-anchor evidence, " +
      "and the audit-chain export), an auditor can independently confirm the " +
      "recorded enforcement history with the shipped standalone " +
      "`verify-transparency` tool, on a separate machine, using only the " +
      "bundle and an out-of-band copy of the public key.",
    "",
  ].join("\n");
  return { title: "Verifying this pack", markdown: body };
}

// ── Section 11: scope and limits (mandatory) ─────────────────────────

function renderScopeAndLimits(): PackSection {
  const body = [
    "# Scope and limits (what this report does and does not prove)",
    "",
    "This honesty page is mandatory. Read it before relying on the report.",
    "",
    "- **Inventory is not exhaustive.** Only wrapped harnesses, gated egress, " +
      "and (on enforced machines) observed destinations are visible. Browser " +
      "ChatGPT, Copilot inside Office, and phones are not.",
    "- **No wire-level proof.** A checkpoint proves the recorded enforcement " +
      "history, not packets blocked on the wire. Per-machine authenticity " +
      "basis can differ (per-event producer-signed on Linux; " +
      "channel-authenticated on macOS).",
    "- **We do not claim per-rule per-flow auditing.** The shipped claim is: " +
      "enforces a signed operator policy, with a tamper-evident log and " +
      "signed enforcement-activity totals.",
    "- **Freshness.** A stale but genesis-rooted bundle can still pass offline " +
      "verification; only opt-in public anchoring plus a pinned log key gives " +
      "an auditor freshness and fork detection.",
    "- **Self-reported binary hash; no remote attestation.**",
    "- **Covered window (both ends).** Audit retention is size/count-based " +
      "(FIFO), not time-based, so a busy fortress can prune early-quarter " +
      "entries (start-side shortfall); and a report generated before the " +
      "quarter closes can only attest coverage through its generation time " +
      "(end-side / partial-quarter shortfall). This report detects and " +
      "discloses both above and states the real covered-through instant, " +
      "never assuming coverage to the quarter end.",
    "- **Human vs automated decisions are separated.** Human control-point " +
      "approvals/denials are counted apart from automated-tier decisions. The " +
      "denial figure is blended (one shared audit operation) and is not " +
      "claimed to be purely automated enforcement.",
    "- **Human-review counts** reflect the control-point operator gate, not " +
      "a supervising attorney's per-matter review.",
    "- **Attestations prove acknowledgment, not competence.**",
    "- **Not legal advice, no carrier endorsement.**",
    "",
  ].join("\n");
  return { title: "Scope and limits", markdown: body };
}

