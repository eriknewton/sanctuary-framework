import type {
  CustodyFacts,
  EvidencePackInput,
  InventorySnapshot,
  QuarterAggregation,
  ShortfallReport,
} from "./types.js";
import type { QuarterWindow } from "./types.js";

/** One rendered section: a title (PDF page heading) plus its Markdown body. */
export interface PackSection {
  title: string;
  markdown: string;
}

const PLACEHOLDER_BADGE =
  "_[NOT YET INCLUDED IN THIS PREVIEW - a later build slice fills this " +
  "section; it is intentionally blank rather than fabricated.]_";

/** Static disclaimer carried on the cover and in the manifest. */
export const PACK_DISCLAIMER =
  "This evidence pack is a technical artifact generated by the Sanctuary " +
  "Framework. It is NOT legal advice and does not constitute a legal " +
  "interpretation of any professional-responsibility rule, insurance " +
  "questionnaire, or outside-counsel guideline. The mapping to carrier " +
  "questions is Sanctuary's reading of the supplement, not a carrier " +
  "endorsement. Have the policy and attestation content reviewed by a " +
  "licensed attorney before first use.";

function fmtCustodyMode(custody: CustodyFacts | undefined): string {
  switch (custody?.custody_mode) {
    case "passphrase":
      return "passphrase held by the firm";
    case "keychain":
      return "operating-system keychain on the firm's machine";
    default:
      return "not reported by this install";
  }
}

// ── Section 1: cover ─────────────────────────────────────────────────

function renderCover(
  input: EvidencePackInput,
  window: QuarterWindow,
  generatedAt: string,
  signerDid: string,
  productName: string,
  shortfall: ShortfallReport
): PackSection {
  const body = [
    `# ${productName}`,
    "",
    `**Firm:** ${input.firm_name}`,
    "",
    `**Reporting quarter:** ${window.label} (${window.start_inclusive} to ${window.end_exclusive}, end exclusive)`,
    "",
    `**Generated:** ${generatedAt}`,
    "",
    `**Coverage attested through:** ${shortfall.covered_to_exclusive} (exclusive)`,
    "",
    `**Signer identity:** ${signerDid}`,
    "",
  ];
  if (shortfall.in_progress_quarter) {
    body.push(
      "> PARTIAL QUARTER: this report was generated before " +
        window.label +
        " ended. It covers only the portion of the quarter through the " +
        "generation time above, NOT the full quarter. Regenerate after the " +
        "quarter closes for a complete report.",
      ""
    );
  }
  body.push(
    "This document answers, one for one, the five questions a legal " +
      "malpractice carrier now asks about AI use, and gives a third party " +
      "the instructions to verify the underlying evidence without trusting " +
      "the vendor.",
    "",
    "## Disclaimer",
    "",
    PACK_DISCLAIMER
  );
  return { title: productName, markdown: body.join("\n") };
}

// ── Section 2: executive summary ─────────────────────────────────────

function renderExecutiveSummary(
  agg: QuarterAggregation,
  shortfall: ShortfallReport,
  inv: InventorySnapshot
): PackSection {
  const machines = "1 (this Sanctuary install)";
  const c = agg.by_category;
  const toolCount = (inv.agents?.length ?? 0) + (inv.mcp_servers?.length ?? 0);
  const humanApproved = c.human_approved;
  const humanDenied = c.human_denied;
  const humanReviewed = humanApproved + humanDenied;
  const autoAllowed = c.allowed + c.allowed_proxy;
  const blendedDenied = c.denied;
  const autoBlocked = c.injection_blocked;
  const toolLine =
    toolCount === 0
      ? "**AI tools inventoried:** 0 in this preview " +
        "(live enumeration of wrapped harnesses and connected AI tool servers " +
        "is wired in a later slice; see the inventory section for the coverage " +
        "basis - this is NOT a claim that the firm uses no AI tools)."
      : `**AI tools inventoried:** ${toolCount} ` +
        "(wrapped harnesses and connected AI tool servers this install can " +
        "see; see the inventory section for coverage limits).";

  const lines = [
    "# Executive summary",
    "",
    "In plain terms, for the reporting quarter:",
    "",
    `- **Machines covered:** ${machines}.`,
    `- ${toolLine}`,
    `- **Actions reviewed by a human at the control point:** ${humanReviewed} ` +
      `(${humanApproved} approved, ${humanDenied} denied through the inbox).`,
    `- **Automated decisions:** ${autoAllowed} allowed, ${autoBlocked} blocked as ` +
      "prompt injection.",
    `- **Denied (automated policy or human control point):** ${blendedDenied} ` +
      "(these share one audit operation and cannot be split here; see section 6).",
    `- **Total recorded control-point decisions in the quarter:** ${agg.total_in_window}.`,
    "- **Unresolved incidents:** none surfaced by this preview " +
      "(the incident-response section is a labeled placeholder in this build).",
    "",
  ];
  if (shortfall.shortfall) {
    lines.push("> COVERAGE NOTICE: " + shortfall.explanation, "");
  }
  lines.push(
    "These counts reflect enforcement decisions at Sanctuary's control " +
      "point. They show that a human was in the loop for gated actions; they " +
      "do not, by themselves, prove that a supervising attorney reviewed the " +
      "output of each client matter. The written policy and per-attorney " +
      "attestations carry that half.",
    ""
  );
  return { title: "Executive summary", markdown: lines.join("\n") };
}

// ── Section 3: AI tool inventory (CNA Q1) ────────────────────────────

function renderInventory(inv: InventorySnapshot): PackSection {
  const lines = [
    "# AI tool inventory",
    "",
    "_Answers CNA Question 1: which AI tools are used._",
    "",
    "## Coverage basis (read this first)",
    "",
    "Sanctuary can enumerate only what it wraps, what flows through its " +
      "gates, and (on enforced machines) the destinations its observe engine " +
      "records. An attorney using ChatGPT in a browser tab, or Copilot inside " +
      "Word, is INVISIBLE to this inventory. This section must never be read " +
      "as an exhaustive list of AI use at the firm; the written policy and " +
      "per-attorney attestations cover unmanaged use.",
    "",
  ];

  const agents = inv.agents ?? [];
  lines.push("## Wrapped AI harnesses");
  lines.push("");
  if (agents.length === 0) {
    lines.push(
      "This preview did not enumerate wrapped harnesses from the hub agent " +
        "registry. " + PLACEHOLDER_BADGE
    );
  } else {
    lines.push("| Agent | Harness | Model | Wrapped | Status |");
    lines.push("|---|---|---|---|---|");
    for (const a of agents) {
      const model = [a.model_vendor, a.model_id].filter(Boolean).join(" / ") || "-";
      lines.push(
        `| ${a.agent_id} | ${a.harness} | ${model} | ${a.wrapped_at ?? "-"} | ${a.status ?? "-"} |`
      );
    }
  }
  lines.push("");

  const servers = inv.mcp_servers ?? [];
  lines.push("## Connected AI tool servers (MCP)");
  lines.push("");
  if (servers.length === 0) {
    lines.push(
      "This preview did not enumerate connected MCP servers. " +
        PLACEHOLDER_BADGE
    );
  } else {
    lines.push("| Server | Transport | State | Tools |");
    lines.push("|---|---|---|---|");
    for (const s of servers) {
      lines.push(
        `| ${s.name} | ${s.transport ?? "-"} | ${s.connection_state ?? "-"} | ${s.tool_count ?? "-"} |`
      );
    }
  }
  lines.push("");

  const dests = inv.observed_destinations ?? [];
  lines.push("## Observed egress destinations (enforced machines only)");
  lines.push("");
  if (dests.length === 0) {
    lines.push(
      "This preview did not include observed egress destinations. " +
        PLACEHOLDER_BADGE
    );
  } else {
    lines.push("| Destination | Port | Protocol | Seen | Exfil risk |");
    lines.push("|---|---|---|---|---|");
    for (const d of dests) {
      lines.push(
        `| ${d.host} | ${d.port ?? "-"} | ${d.protocol ?? "-"} | ${d.times_seen ?? "-"} | ${d.exfil_risk ? "yes" : "no"} |`
      );
    }
  }
  lines.push("");
  return { title: "AI tool inventory", markdown: lines.join("\n") };
}

