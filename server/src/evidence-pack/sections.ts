/**
 * Render the full ordered section list for the pack. `productName` is the
 * working title on the cover. The returned sections feed both the signed
 * Markdown report and the PDF (one PDF page-group per section).
 */
export function renderSections(params: {
  input: EvidencePackInput;
  window: QuarterWindow;
  generatedAt: string;
  signerDid: string;
  productName: string;
  aggregation: ReadOutcome<QuarterAggregation>;
  shortfall: ReadOutcome<ShortfallReport>;
  custody: ReadOutcome<CustodyFacts>;
  inventory?: InventorySnapshot;
  discreteExports: DiscreteExportsView;
}): PackSection[] {
  const inv = params.inventory ?? emptyInventorySnapshot();
  return [
    renderCover(
      params.input,
      params.window,
      params.generatedAt,
      params.signerDid,
      params.productName,
      params.shortfall
    ),
    renderExecutiveSummary(params.aggregation, params.shortfall, inv),
    renderInventory(inv),
    renderGovernancePolicy(),
    renderTrainingAttestations(),
    renderHumanReview(params.aggregation),
    renderAccessLog(params.aggregation, params.shortfall),
    renderCustody(params.custody),
    renderIncidentResponse(),
    renderVerification(params.signerDid, params.discreteExports),
    renderScopeAndLimits(),
    renderPerMachineAppendix(),
  ];
}
