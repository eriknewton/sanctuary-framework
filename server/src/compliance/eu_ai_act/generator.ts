/**
 * The cryptographic attestations document references the
 * already-generated files' hashes and signatures. It MUST be
 * rendered after all other documents.
 */
function renderAttestations(
  baseContext: TemplateContext,
  priorFiles: BundleFile[],
  manifestSha256: string,
  manifestSignature: string,
  ds: DocSigner
): BundleFile {
  const table = [
    "| Filename | SHA-256 | Signature (base64url) |",
    "|---|---|---|",
    ...priorFiles.map(
      (f) => `| \`${f.filename}\` | \`${f.sha256}\` | \`${f.signature ?? ""}\` |`
    ),
  ].join("\n");

  const context: TemplateContext = {
    ...baseContext,
    file_attestation_table: table,
    manifest_sha256: manifestSha256,
    manifest_signature: manifestSignature,
    document_title: "Cryptographic Attestations",
    document_subtitle:
      "Bundle integrity attestations signed by the provider's primary Ed25519 identity",
  };

  return finaliseDocument(
    CRYPTOGRAPHIC_ATTESTATIONS_TEMPLATE,
    context,
    "06_cryptographic_attestations.md",
    ds
  );
}

// ── Manifest builder ─────────────────────────────────────────────────

function buildManifest(
  input: ComplianceBundleInput,
  generatedAt: string,
  signer: StoredIdentity,
  files: BundleFile[],
  ds: DocSigner
): BundleManifest {
  const stats = coverageStats(COVERAGE_MATRIX_V1);

  const rowSummaries: ManifestRowSummary[] = COVERAGE_MATRIX_V1.rows.map(
    (r) => ({
      id: r.id,
      clause_id: r.citation.clause_id,
      coverage: r.coverage,
      evidence_emitter: [...r.evidence_emitter],
    })
  );

  // Build the manifest body without the signature (to be signed).
  const manifestBody: Omit<BundleManifest, "manifest_signature"> = {
    bundle_version: "1.0",
    matrix_version: "v1",
    regulation_version: REGULATION_VERSION,
    generated_at: generatedAt,
    agent_did: input.agent_did,
    period_start: input.period_start,
    period_end: input.period_end,
    deployment_context: input.deployment_context,
    signer: {
      did: signer.did,
      public_key_base64url: signer.public_key,
    },
    files: files.map((f) => ({
      filename: f.filename,
      content_type: f.content_type,
      sha256: f.sha256,
      signature: f.signature ?? "",
    })),
    coverage_summary: {
      total_rows: stats.total_rows,
      full: stats.full,
      partial: stats.partial,
      manual_only: stats.manual_only,
      full_pct: stats.full_pct,
      partial_pct: stats.partial_pct,
      manual_only_pct: stats.manual_only_pct,
    },
    coverage_rows: rowSummaries,
    disclaimer: NOT_LEGAL_ADVICE_DISCLAIMER,
  };

  // Sign the canonical JSON of the manifest body.
  const canonical = canonicalJSON(manifestBody);
  const manifestSignature = ds.signContent(canonical);

  return {
    ...manifestBody,
    manifest_signature: manifestSignature,
  };
}

// ── Top-level generator entry point ──────────────────────────────────

/**
 * Generate a complete EU AI Act compliance bundle for the given
 * agent and reporting period.
 */
export async function generateEuAiActBundle(
  input: ComplianceBundleInput,
  deps: GeneratorDeps
): Promise<ComplianceBundle> {
  // Resolve primary identity.
  const signer = deps.identityManager.getDefault();
  if (!signer) {
    throw new Error(
      "No primary identity configured. Run identity_create and " +
        "identity_set_primary before generating a compliance bundle."
    );
  }

  const ds = makeSigner(signer, deps.masterKey);

  // Compute audit period summary.
  const auditSummary = await computeAuditPeriodSummary(
    deps.auditLog,
    input.period_start,
    input.period_end
  );

  const generatedAt = input.generated_at_override ?? new Date().toISOString();

  // Build the shared template context.
  const baseContext = buildCommonContext(
    input,
    deps,
    signer,
    auditSummary,
    generatedAt
  );

  // Render documents 1-5 in order.
  const doc1 = renderAnnexIV(baseContext, ds);
  const doc2 = renderArticle26(baseContext, ds);
  const doc3 = renderArticle12(baseContext, ds);
  const doc4 = renderRiskManagement(baseContext, ds);
  const doc5 = renderHumanOversight(baseContext, ds);

  // Build a partial manifest with docs 1-5 (and a placeholder for
  // doc 6) so we can compute its canonical hash and signature for
  // inclusion in doc 6.
  //
  // Doc 6 references the manifest SHA-256 and signature, which
  // include every file's hash. Doc 6 cannot include its OWN hash
  // and signature inside the manifest it references, because that
  // would create a cyclic dependency. Resolution:
  //
  // 1. Build the manifest with docs 1-5 only.
  // 2. Render doc 6 with that partial manifest's hash/signature.
  // 3. Rebuild the manifest with all 6 docs (doc 6 is now included).
  // 4. The final bundle's manifest_signature covers all 6 files.
  //
  // The attestations document in step 2 references the manifest
  // hash from step 1, which is the hash-over-docs-1-5. The final
  // manifest in step 3 supersedes that with a hash-over-all-6.
  // Verifiers must check the final manifest; the intermediate hash
  // in doc 6's body is a narrative reference only.

  const partialManifest = buildManifest(
    input,
    generatedAt,
    signer,
    [doc1, doc2, doc3, doc4, doc5],
    ds
  );
  const partialCanonical = canonicalJSON(partialManifest);
  const partialSha256 = ds.sha256Hex(partialCanonical);
  const partialSignature = partialManifest.manifest_signature;

  const doc6 = renderAttestations(
    baseContext,
    [doc1, doc2, doc3, doc4, doc5],
    partialSha256,
    partialSignature,
    ds
  );

  const allFiles = [doc1, doc2, doc3, doc4, doc5, doc6];

  // Final manifest covers all 6 files.
  const finalManifest = buildManifest(
    input,
    generatedAt,
    signer,
    allFiles,
    ds
  );

  return {
    manifest: finalManifest,
    files: allFiles,
  };
}

