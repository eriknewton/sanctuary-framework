// ── Canonical JSON (sorted keys, no whitespace) ──────────────────────

/**
 * Deterministic canonical JSON serialisation for signing. Sorts keys
 * recursively and emits with no whitespace.
 */
function canonicalJSON(value: unknown): string {
  return JSON.stringify(sortKeys(value));
}

function sortKeys(value: unknown): unknown {
  if (value === null || typeof value !== "object") return value;
  if (Array.isArray(value)) return value.map(sortKeys);
  const sorted: Record<string, unknown> = {};
  const obj = value as Record<string, unknown>;
  for (const key of Object.keys(obj).sort()) {
    sorted[key] = sortKeys(obj[key]);
  }
  return sorted;
}

// ── Audit period summary ─────────────────────────────────────────────

/**
 * Walk the audit log for the reporting period and compute
 * aggregate statistics for the templates.
 */
export async function computeAuditPeriodSummary(
  auditLog: AuditLog,
  periodStart: string,
  periodEnd: string
): Promise<AuditPeriodSummary> {
  // Query as broadly as possible, then filter client-side for
  // the end date. The audit log query API supports `since` but not
  // `until` — so we pull everything since period_start and filter
  // by period_end in memory.
  const { entries: rawEntries } = await auditLog.query({
    since: periodStart,
    limit: 1_000_000, // effectively unbounded for this period
  });

  const endTime = new Date(periodEnd).getTime();
  const entries = rawEntries.filter(
    (e: AuditEntry) => new Date(e.timestamp).getTime() <= endTime
  );

  const byLayer: Record<"l1" | "l2" | "l3" | "l4", number> = {
    l1: 0,
    l2: 0,
    l3: 0,
    l4: 0,
  };
  const gate = {
    allow: 0,
    allow_proxy: 0,
    deny: 0,
    escalate: 0,
    unclassified: 0,
  };
  let injection = 0;
  const operationSet = new Set<string>();
  const identitySet = new Set<string>();

  for (const entry of entries) {
    byLayer[entry.layer]++;
    operationSet.add(entry.operation);
    identitySet.add(entry.identity_id);

    if (entry.operation.startsWith("gate_allow_proxy:")) {
      gate.allow_proxy++;
    } else if (entry.operation.startsWith("gate_allow:")) {
      gate.allow++;
    } else if (entry.operation.startsWith("gate_deny:")) {
      gate.deny++;
    } else if (entry.operation.startsWith("gate_escalate:")) {
      gate.escalate++;
    } else if (entry.operation.startsWith("gate_unclassified:")) {
      gate.unclassified++;
    } else if (entry.operation.startsWith("injection_detected:")) {
      injection++;
    }
  }

  return {
    period_start: periodStart,
    period_end: periodEnd,
    total_entries: entries.length,
    entries_by_layer: byLayer,
    gate_decisions: gate,
    injection_detected: injection,
    unique_operations: Array.from(operationSet).sort(),
    unique_identities: Array.from(identitySet).sort(),
  };
}

// ── Row block rendering ──────────────────────────────────────────────

/**
 * Pre-render one coverage matrix row into a Markdown block using the
 * shared ROW_BLOCK_TEMPLATE.
 */
function renderRowBlock(row: CoverageRow): string {
  const citation = `${row.citation.instrument} ${row.citation.section}`;
  return render(ROW_BLOCK_TEMPLATE, {
    row_citation: citation,
    row_title: row.citation.title,
    row_coverage_badge: coverageBadge(row.coverage),
    regulation_version: REGULATION_VERSION,
    row_requirement: row.requirement,
    row_evidence_emitted: row.evidence_emitted,
    row_evidence_emitter_list: formatEmitterList(row.evidence_emitter),
    row_manual_carveout:
      row.manual_carveout ?? "_(none — this row is fully auto-emitted)_",
  });
}

/**
 * Render an array of rows as concatenated row blocks.
 */
function renderRowBlocks(rows: CoverageRow[]): string {
  return rows.map(renderRowBlock).join("");
}

// ── Row filters by citation ──────────────────────────────────────────

function rowsWithCitationPrefix(prefix: string): CoverageRow[] {
  return COVERAGE_MATRIX_V1.rows.filter((r) =>
    r.citation.clause_id.startsWith(prefix)
  );
}

function rowsById(ids: string[]): CoverageRow[] {
  const set = new Set(ids);
  return COVERAGE_MATRIX_V1.rows.filter((r) => set.has(r.id));
}

