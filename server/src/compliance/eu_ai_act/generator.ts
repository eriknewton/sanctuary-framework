// ── Document renderers ───────────────────────────────────────────────

interface DocSigner {
  signContent: (content: string) => string;
  sha256Hex: (content: string) => string;
}

// NOTE: SignerView interface was removed during the first typecheck
// pass — signer fields are carried through the base template context
// (signer_did, signer_pubkey) rather than as a separate parameter.

function makeSigner(
  signer: StoredIdentity,
  masterKey: Uint8Array
): DocSigner {
  const encryptionKey = derivePurposeKey(masterKey, "identity-encryption");
  return {
    signContent: (content: string) => {
      const digest = hash(stringToBytes(content));
      const sig = sign(digest, signer.encrypted_private_key, encryptionKey);
      return toBase64url(sig);
    },
    sha256Hex: (content: string) => bytesToHex(hash(stringToBytes(content))),
  };
}

/**
 * Finalise a document: render the template once, hash the rendered
 * bytes with SHA-256, and sign the hash with the provider's primary
 * Ed25519 identity. The document body itself does not contain the
 * hash or signature — those live only in the bundle manifest and in
 * the returned BundleFile.sha256 / BundleFile.signature fields.
 *
 * Verification is trivial: SHA-256(file.content) === file.sha256,
 * and Ed25519.verify(file.signature, file.sha256, signer_pubkey).
 * No special knowledge of Sanctuary internals is required.
 */
function finaliseDocument(
  template: string,
  context: TemplateContext,
  filename: string,
  ds: DocSigner
): BundleFile {
  const content = render(template, context);
  const sha256Hex = ds.sha256Hex(content);
  const signature = ds.signContent(content);

  return {
    filename,
    content,
    content_type: "text/markdown",
    sha256: sha256Hex,
    signature,
  };
}

// ── Per-document renderers ───────────────────────────────────────────

function renderAnnexIV(
  baseContext: TemplateContext,
  ds: DocSigner
): BundleFile {
  // Group Annex IV rows by section number for the template slots.
  const sections: Record<string, string> = {};
  for (let n = 1; n <= 9; n++) {
    const sectionRows = rowsWithCitationPrefix(`annex-iv-${n}`);
    sections[`sections_${n}`] =
      sectionRows.length > 0
        ? renderRowBlocks(sectionRows)
        : "_(no rows in this section)_\n\n";
  }

  const context: TemplateContext = {
    ...baseContext,
    ...sections,
    document_title: "Annex IV Technical Documentation",
    document_subtitle:
      "Prepared under Article 11 of Regulation (EU) 2024/1689",
  };

  return finaliseDocument(
    ANNEX_IV_TECHNICAL_DOCUMENTATION_TEMPLATE,
    context,
    "01_annex_iv_technical_documentation.md",
    ds
  );
}

