// ── Manifest builder ─────────────────────────────────────────────────

function buildManifest(
  input: ComplianceBundleInput,
  generatedAt: string,
  signer: StoredIdentity,
  files: BundleFile[],
  ds: DocSigner
): BundleManifest {
  const stats = coverageStats(COVERAGE_MATRIX_V1);

  const rowSummaries: ManifestRowSummary[] = COVERAGE_MATRIX_V1.rows.map(
    (r) => ({
      id: r.id,
      clause_id: r.citation.clause_id,
      coverage: r.coverage,
      evidence_emitter: [...r.evidence_emitter],
    })
  );

  // Build the manifest body without the signature (to be signed).
  const manifestBody: Omit<BundleManifest, "manifest_signature"> = {
    bundle_version: "1.0",
    matrix_version: "v1",
    regulation_version: REGULATION_VERSION,
    generated_at: generatedAt,
    agent_did: input.agent_did,
    period_start: input.period_start,
    period_end: input.period_end,
    deployment_context: input.deployment_context,
    signer: {
      did: signer.did,
      public_key_base64url: signer.public_key,
    },
    files: files.map((f) => ({
      filename: f.filename,
      content_type: f.content_type,
      sha256: f.sha256,
      signature: f.signature ?? "",
    })),
    coverage_summary: {
      total_rows: stats.total_rows,
      full: stats.full,
      partial: stats.partial,
      manual_only: stats.manual_only,
      full_pct: stats.full_pct,
      partial_pct: stats.partial_pct,
      manual_only_pct: stats.manual_only_pct,
    },
    coverage_rows: rowSummaries,
    disclaimer: NOT_LEGAL_ADVICE_DISCLAIMER,
  };

  // Sign the canonical JSON of the manifest body.
  const canonical = canonicalJSON(manifestBody);
  const manifestSignature = ds.signContent(canonical);

  return {
    ...manifestBody,
    manifest_signature: manifestSignature,
  };
}

// ── Delta computation ────────────────────────────────────────────────

/**
 * Attempt to load a prior bundle manifest from disk. Returns null
 * and pushes a warning into the output array if the path is
 * unreadable or the file is not a valid bundle manifest. Never
 * throws — delta problems must never fail bundle generation.
 */
async function loadPriorBundleManifest(
  bundlePath: string,
  warnings: string[]
): Promise<BundleManifest | null> {
  try {
    const manifestPath = join(bundlePath, "00_bundle_manifest.json");
    const bytes = await readFile(manifestPath, "utf-8");
    const parsed = JSON.parse(bytes) as BundleManifest;
    if (
      typeof parsed.bundle_version !== "string" ||
      typeof parsed.regulation_version !== "string" ||
      !Array.isArray(parsed.coverage_rows)
    ) {
      warnings.push(
        `Prior bundle at ${bundlePath} is missing required manifest fields; delta skipped.`
      );
      return null;
    }
    return parsed;
  } catch (e) {
    warnings.push(
      `Prior bundle at ${bundlePath} could not be read: ${(e as Error).message}. Delta skipped.`
    );
    return null;
  }
}

/**
 * Compute the structured delta between a prior and current
 * manifest. Per Erik's Phase 2 spec, this focuses on four change
 * categories: regulation_version bump, coverage flag changes,
 * evidence_emitter array changes, and last_reviewed_date advances.
 *
 * The current manifest does not carry last_reviewed_date in
 * ManifestRowSummary (it's only in the source matrix), so
 * last_reviewed_date comparison uses the live matrix as the
 * authoritative current state and compares to the prior manifest's
 * coverage_rows entries if they carry the field. If the prior
 * manifest does not expose last_reviewed_date per row, that field
 * is omitted from the delta (no false positives).
 */
function computeDelta(
  prior: BundleManifest,
  current: BundleManifest,
  priorBundlePath: string,
  warnings: string[]
): DeltaReport {
  const priorRows = new Map(prior.coverage_rows.map((r) => [r.id, r]));
  const currentRows = new Map(current.coverage_rows.map((r) => [r.id, r]));

  const rows_added: string[] = [];
  const rows_removed: string[] = [];
  const rows_changed: DeltaRowChange[] = [];

  for (const [id] of currentRows) {
    if (!priorRows.has(id)) {
      rows_added.push(id);
    }
  }
  for (const [id] of priorRows) {
    if (!currentRows.has(id)) {
      rows_removed.push(id);
    }
  }

  for (const [id, currentRow] of currentRows) {
    const priorRow = priorRows.get(id);
    if (!priorRow) continue;
    const changes: DeltaRowChange["changes"] = {};
    if (priorRow.coverage !== currentRow.coverage) {
      changes.coverage = {
        from: priorRow.coverage,
        to: currentRow.coverage,
      };
    }
    const priorEmitters = [...(priorRow.evidence_emitter || [])].sort();
    const currentEmitters = [...(currentRow.evidence_emitter || [])].sort();
    if (JSON.stringify(priorEmitters) !== JSON.stringify(currentEmitters)) {
      changes.evidence_emitter = {
        from: priorRow.evidence_emitter || [],
        to: currentRow.evidence_emitter || [],
      };
    }
    if (Object.keys(changes).length > 0) {
      rows_changed.push({
        row_id: id,
        clause_id: currentRow.clause_id,
        changes,
      });
    }
  }

  rows_added.sort();
  rows_removed.sort();
  rows_changed.sort((a, b) => a.row_id.localeCompare(b.row_id));

  return {
    prior_bundle_path: priorBundlePath,
    prior_generated_at: prior.generated_at,
    prior_signer_did: prior.signer.did,
    prior_regulation_version: prior.regulation_version,
    prior_matrix_version: prior.matrix_version,
    current_generated_at: current.generated_at,
    current_signer_did: current.signer.did,
    current_regulation_version: current.regulation_version,
    current_matrix_version: current.matrix_version,
    regulation_version_changed:
      prior.regulation_version !== current.regulation_version,
    matrix_version_changed:
      prior.matrix_version !== current.matrix_version,
    rows_added,
    rows_removed,
    rows_changed,
    warnings,
  };
}

/**
 * Format a DeltaReport's three row-change sections as Markdown
 * blocks for embedding in the delta template.
 */
function formatDeltaSections(report: DeltaReport): {
  rows_added_rendered: string;
  rows_removed_rendered: string;
  rows_changed_rendered: string;
  warnings_rendered: string;
  no_changes_note: string;
} {
  const added =
    report.rows_added.length === 0
      ? "_(none)_"
      : report.rows_added.map((id) => `- \`${id}\``).join("\n");

  const removed =
    report.rows_removed.length === 0
      ? "_(none)_"
      : report.rows_removed.map((id) => `- \`${id}\``).join("\n");

  const changed =
    report.rows_changed.length === 0
      ? "_(none)_"
      : report.rows_changed
          .map((rc) => {
            const lines = [
              `#### \`${rc.row_id}\` (${rc.clause_id})`,
              "",
            ];
            if (rc.changes.coverage) {
              lines.push(
                `- **coverage:** \`${rc.changes.coverage.from}\` → \`${rc.changes.coverage.to}\``
              );
            }
            if (rc.changes.evidence_emitter) {
              lines.push(
                `- **evidence_emitter from:** [${rc.changes.evidence_emitter.from.map((e) => `\`${e}\``).join(", ")}]`
              );
              lines.push(
                `- **evidence_emitter to:** [${rc.changes.evidence_emitter.to.map((e) => `\`${e}\``).join(", ")}]`
              );
            }
            if (rc.changes.last_reviewed_date) {
              lines.push(
                `- **last_reviewed_date:** ${rc.changes.last_reviewed_date.from} → ${rc.changes.last_reviewed_date.to}`
              );
            }
            lines.push("");
            return lines.join("\n");
          })
          .join("\n");

  const warningsList =
    report.warnings.length === 0
      ? "_(none)_"
      : report.warnings.map((w) => `- ${w}`).join("\n");

  const hasAnyChanges =
    report.regulation_version_changed ||
    report.matrix_version_changed ||
    report.rows_added.length > 0 ||
    report.rows_removed.length > 0 ||
    report.rows_changed.length > 0;

  const noChangesNote = hasAnyChanges
    ? ""
    : "**No changes detected between prior and current bundle.** Both bundles reference the same regulation_version, the same matrix_version, and the same row set with identical coverage flags and evidence_emitter arrays. The only differences are the generation timestamps and the audit period activity captured in documents 02-05.\n\n";

  return {
    rows_added_rendered: added,
    rows_removed_rendered: removed,
    rows_changed_rendered: changed,
    warnings_rendered: warningsList,
    no_changes_note: noChangesNote,
  };
}

function renderDelta(
  baseContext: TemplateContext,
  report: DeltaReport,
  ds: DocSigner
): BundleFile {
  const sections = formatDeltaSections(report);
  const context: TemplateContext = {
    ...baseContext,
    prior_bundle_path: report.prior_bundle_path,
    prior_generated_at: report.prior_generated_at,
    prior_signer_did: report.prior_signer_did,
    prior_regulation_version: report.prior_regulation_version,
    prior_matrix_version: report.prior_matrix_version,
    current_generated_at: report.current_generated_at,
    current_signer_did: report.current_signer_did,
    current_regulation_version: report.current_regulation_version,
    current_matrix_version: report.current_matrix_version,
    regulation_version_changed: report.regulation_version_changed
      ? "yes"
      : "no",
    matrix_version_changed: report.matrix_version_changed ? "yes" : "no",
    rows_added_count: report.rows_added.length,
    rows_removed_count: report.rows_removed.length,
    rows_changed_count: report.rows_changed.length,
    ...sections,
    document_title: "Compliance Bundle Delta Report",
    document_subtitle:
      "Changes between the prior bundle and this bundle",
  };
  return finaliseDocument(
    DELTA_TEMPLATE,
    context,
    "08_delta.md",
    ds
  );
}

// ── Verascore publish hook ───────────────────────────────────────────

/**
 * Allowed Verascore hostnames for the SSRF allow-list. Matches the
 * set used by `reputation_publish` in `src/reputation/tools.ts`.
 * Mirrored here rather than imported so the compliance generator
 * does not couple to the reputation module's internals.
 */
const ALLOWED_VERASCORE_HOSTS = new Set([
  "verascore.ai",
  "www.verascore.ai",
  "api.verascore.ai",
]);

/**
 * Publish a signed bundle manifest to Verascore as a pure side-
 * effect. Follows the same wire format and signing path used by
 * `reputation_publish`:
 *
 *   - Allow-list SSRF check (HTTPS + known Verascore host)
 *   - Canonical JSON of the manifest is signed with the provider's
 *     primary Ed25519 identity via the existing core/identity.js
 *     sign() primitive — no second signing pipeline
 *   - POST { agentId, signature, publicKey, type, data } to
 *     `${verascoreUrl}/api/publish` with type "eu-ai-act-bundle"
 *   - Only the manifest is published; document bodies never leave
 *     the local filesystem
 *
 * NON-DEPENDENCY PRINCIPLE: this function MUST NOT throw. Any
 * error (URL validation, fetch failure, non-2xx response) is
 * captured in the returned VerascorePublishResult and bundle
 * generation proceeds unaffected. Sanctuary never requires
 * Verascore to be online.
 */
async function publishBundleManifestToVerascore(
  manifest: BundleManifest,
  signer: StoredIdentity,
  encryptionKey: Uint8Array,
  verascoreUrl: string,
  ds: DocSigner
): Promise<VerascorePublishResult> {
  const result: VerascorePublishResult = {
    attempted: true,
    published: false,
    verascore_url: verascoreUrl,
  };

  // Validate URL shape + SSRF allow-list.
  let parsed: URL;
  try {
    parsed = new URL(verascoreUrl);
  } catch {
    result.error = `Verascore URL is not a valid URL: ${verascoreUrl}`;
    return result;
  }
  if (parsed.protocol !== "https:") {
    result.error = `Verascore URL must use HTTPS (got ${parsed.protocol})`;
    return result;
  }
  if (!ALLOWED_VERASCORE_HOSTS.has(parsed.hostname)) {
    result.error = `Verascore URL must point to a known Verascore host (${[...ALLOWED_VERASCORE_HOSTS].join(", ")}). Got: ${parsed.hostname}`;
    return result;
  }

  // Build canonical manifest bytes and sign them for the publish
  // request body. The manifest already carries its own
  // manifest_signature field (over canonical body with the signature
  // stripped); Verascore's API additionally requires a signature
  // over the outer request body, so we sign once more — same
  // identity, same key, same sign() primitive.
  const canonicalManifest = canonicalJSON(manifest);
  const manifestBytes = stringToBytes(canonicalManifest);
  const manifestSha256 = ds.sha256Hex(canonicalManifest);
  result.published_manifest_sha256 = manifestSha256;

  let requestSignatureB64: string;
  try {
    const sigBytes = sign(
      manifestBytes,
      signer.encrypted_private_key,
      encryptionKey
    );
    requestSignatureB64 = toBase64url(sigBytes);
  } catch (e) {
    result.error = `Failed to sign Verascore publish payload: ${(e as Error).message}`;
    return result;
  }

  // Derive a Verascore-slug agent ID from the manifest's agent DID
  // using the same normalisation reputation_publish uses.
  const agentId = manifest.agent_did
    .replace(/[^a-zA-Z0-9-]/g, "-")
    .toLowerCase();
  result.verascore_agent_id = agentId;

  const requestBody = {
    agentId,
    signature: requestSignatureB64,
    publicKey: signer.public_key,
    type: "eu-ai-act-bundle",
    data: manifest,
  };

  try {
    const response = await fetch(`${verascoreUrl}/api/publish`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(requestBody),
    });
    result.status = response.status;
    if (!response.ok) {
      result.error = `Verascore API returned ${response.status}`;
      return result;
    }
    result.published = true;
    return result;
  } catch (e) {
    result.error = `Verascore fetch failed: ${(e as Error).message}`;
    return result;
  }
}

// ── Top-level generator entry point ──────────────────────────────────

/**
 * Generate a complete EU AI Act compliance bundle for the given
 * agent and reporting period.
 */
export async function generateEuAiActBundle(
  input: ComplianceBundleInput,
  deps: GeneratorDeps
): Promise<ComplianceBundle> {
  // Resolve primary identity.
  const signer = deps.identityManager.getDefault();
  if (!signer) {
    throw new Error(
      "No primary identity configured. Run identity_create and " +
        "identity_set_primary before generating a compliance bundle."
    );
  }

  const ds = makeSigner(signer, deps.masterKey);

  // Compute audit period summary.
  const auditSummary = await computeAuditPeriodSummary(
    deps.auditLog,
    input.period_start,
    input.period_end
  );

  const generatedAt = input.generated_at_override ?? new Date().toISOString();

  // Build the shared template context.
  const baseContext = buildCommonContext(
    input,
    deps,
    signer,
    auditSummary,
    generatedAt
  );

  // Render documents 1-5 in order.
  const doc1 = renderAnnexIV(baseContext, ds);
  const doc2 = renderArticle26(baseContext, ds);
  const doc3 = renderArticle12(baseContext, ds);
  const doc4 = renderRiskManagement(baseContext, ds);
  const doc5 = renderHumanOversight(baseContext, ds);

  // Doc 07 (Annex III classification) is rendered separately from
  // doc 06 (attestations) because it is a content document; doc 06
  // is the integrity attestation document and attests to docs 1-5.
  // Doc 07 is attested via the manifest only (the manifest covers
  // all 7 files with SHA-256 + Ed25519 signatures).
  const doc7 = renderAnnexIIIClassification(
    baseContext,
    input.deployment_context.intended_purpose ?? "",
    ds
  );

  // Build a partial manifest with docs 1-5 (and a placeholder for
  // doc 6) so we can compute its canonical hash and signature for
  // inclusion in doc 6.
  //
  // Doc 6 references the manifest SHA-256 and signature, which
  // include every file's hash. Doc 6 cannot include its OWN hash
  // and signature inside the manifest it references, because that
  // would create a cyclic dependency. Resolution:
  //
  // 1. Build the manifest with docs 1-5 only.
  // 2. Render doc 6 with that partial manifest's hash/signature.
  // 3. Rebuild the manifest with all 6 docs (doc 6 is now included).
  // 4. The final bundle's manifest_signature covers all 6 files.
  //
  // The attestations document in step 2 references the manifest
  // hash from step 1, which is the hash-over-docs-1-5. The final
  // manifest in step 3 supersedes that with a hash-over-all-6.
  // Verifiers must check the final manifest; the intermediate hash
  // in doc 6's body is a narrative reference only.

  const partialManifest = buildManifest(
    input,
    generatedAt,
    signer,
    [doc1, doc2, doc3, doc4, doc5],
    ds
  );
  const partialCanonical = canonicalJSON(partialManifest);
  const partialSha256 = ds.sha256Hex(partialCanonical);
  const partialSignature = partialManifest.manifest_signature;

  const doc6 = renderAttestations(
    baseContext,
    [doc1, doc2, doc3, doc4, doc5],
    partialSha256,
    partialSignature,
    ds
  );

  let allFiles: BundleFile[] = [doc1, doc2, doc3, doc4, doc5, doc6, doc7];

  // Optional doc 08 — delta report (only when delta_from_bundle_path
  // is supplied AND the prior bundle loads cleanly). Delta problems
  // never fail bundle generation: the bundle always lands locally,
  // and delta is a best-effort enrichment layer.
  if (input.delta_from_bundle_path) {
    const deltaWarnings: string[] = [];
    const priorManifest = await loadPriorBundleManifest(
      input.delta_from_bundle_path,
      deltaWarnings
    );
    if (priorManifest !== null) {
      // Build a temporary "current" manifest snapshot for comparison.
      // We need the coverage_rows and version fields; other fields
      // are not compared by computeDelta.
      const currentManifestSnapshot = buildManifest(
        input,
        generatedAt,
        signer,
        allFiles,
        ds
      );
      const report = computeDelta(
        priorManifest,
        currentManifestSnapshot,
        input.delta_from_bundle_path,
        deltaWarnings
      );
      const doc8 = renderDelta(baseContext, report, ds);
      allFiles = [...allFiles, doc8];
    }
  }

  // Final manifest covers all files (7 core + optional doc 08 delta).
  const finalManifest = buildManifest(
    input,
    generatedAt,
    signer,
    allFiles,
    ds
  );

  // Optional Verascore publish side-effect. Runs LAST so the bundle
  // is already fully built and ready to return before we touch the
  // network. If publish fails for any reason, the bundle is returned
  // in the same shape with publish_result describing the failure.
  // Sanctuary bundle generation NEVER depends on Verascore being
  // online — this is the non-dependency principle in action.
  let publishResult: VerascorePublishResult | undefined = undefined;
  if (input.publish_to_verascore) {
    const encryptionKey = derivePurposeKey(
      deps.masterKey,
      "identity-encryption"
    );
    publishResult = await publishBundleManifestToVerascore(
      finalManifest,
      signer,
      encryptionKey,
      input.verascore_url ?? "https://verascore.ai",
      ds
    );
  }

  return {
    manifest: finalManifest,
    files: allFiles,
    publish_result: publishResult,
  };
}

