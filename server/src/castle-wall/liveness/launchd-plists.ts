/**
 * The canary LaunchDaemon and observer LaunchAgent property lists, their
 * well-formed checks, and the system-domain `launchctl print` parser. Every
 * generator here is pure: the canary is a function of one validated account
 * name, the observer agent of its fixed program arguments.
 */
import { createHash } from "node:crypto";
import { dirname, isAbsolute } from "node:path";
import {
  ACCOUNT_NAME_MAX,
  CANARY_CURL_DEADLINE_S,
  CANARY_IP,
  CANARY_LABEL,
  CANARY_PORT,
  CANARY_START_INTERVAL_S,
  OBSERVER_LABEL,
  WATCH_THROTTLE_INTERVAL_S,
} from "./constants.js";

const PLIST_HEADER = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">`;

/** The account-name rule: a POSIX-portable user name, so no byte ever needs escaping. */
const ACCOUNT_NAME_TEXT = /^[A-Za-z_][A-Za-z0-9_.-]*$/;
// eslint-disable-next-line no-control-regex
const CONTROL_TEXT = /[\x00-\x1f\x7f]/;

/** The canary command: curl to the literal canary tuple with no proxy, no retry, no config file and a bounded run. */
export const CANARY_PROGRAM_ARGUMENTS: readonly string[] = Object.freeze([
  "/usr/bin/curl", "-q", "--noproxy", "*", "--retry", "0", "--output", "/dev/null", "--silent",
  "--connect-timeout", String(CANARY_CURL_DEADLINE_S), "--max-time", String(CANARY_CURL_DEADLINE_S),
  `http://${CANARY_IP}:${CANARY_PORT}/`,
]);
/** The canary program; the integrity check compares the loaded job's program with it. */
export const CANARY_PROGRAM = CANARY_PROGRAM_ARGUMENTS[0]!;
/** Where the attended install places the canary. */
export const CANARY_INSTALLED_PLIST_PATH = `/Library/LaunchDaemons/${CANARY_LABEL}.plist`;
/** The staged copy the operator writes into the fortress for the attended install. */
export const CANARY_STAGED_PLIST_NAME = "canary.plist";

/** True when `name` may appear in the canary's `UserName`. */
export function canaryAccountNameValid(name: string): boolean {
  return name.length > 0 && Buffer.byteLength(name) <= ACCOUNT_NAME_MAX && ACCOUNT_NAME_TEXT.test(name);
}

/**
 * Render the canary LaunchDaemon for one account. Every byte except the
 * account name is a design constant.
 * Must match server/test/castle-wall/liveness/fixtures/canary.golden.plist, regenerated by server/scripts/generate-canary-plist.ts.
 */
export function generateCanaryPlist(accountName: string): string {
  // A refused name throws and is never escaped, so no host value can reshape the plist.
  if (!canaryAccountNameValid(accountName)) throw new Error("Canary account name is not a valid account name.");
  return `${PLIST_HEADER}
<dict>
\t<key>Label</key>
\t<string>${CANARY_LABEL}</string>
\t<key>UserName</key>
\t<string>${accountName}</string>
\t<key>ProgramArguments</key>
\t<array>
${CANARY_PROGRAM_ARGUMENTS.map(argument => `\t\t<string>${argument}</string>`).join("\n")}
\t</array>
\t<key>StartInterval</key>
\t<integer>${CANARY_START_INTERVAL_S}</integer>
\t<key>RunAtLoad</key>
\t<true/>
\t<key>ProcessType</key>
\t<string>Background</string>
\t<key>EnvironmentVariables</key>
\t<dict/>
</dict>
</plist>
`;
}

/** The largest valid generator output, so the integrity read cap is computed, never typed. */
export const CANARY_PLIST_BYTES = Buffer.byteLength(generateCanaryPlist("a".repeat(ACCOUNT_NAME_MAX)));

/** Hex SHA-256 of the canary plist for one account. */
export function canaryPlistSha256(accountName: string): string {
  return createHash("sha256").update(generateCanaryPlist(accountName)).digest("hex");
}

// ---------------------------------------------------------------------------
// Observer LaunchAgent.
// ---------------------------------------------------------------------------
/** Interpreter, CLI, group, verb, fortress flag, fortress path, supervision flag. */
const WATCH_PROGRAM_ARGUMENT_COUNT = 7;
/**
 * Path segments that name a version-specific install. One-sided copy of the
 * lexical rule in server/src/cli/stable-runtime-path.ts, which this module may not import.
 */
const UNSTABLE_NODE_SEGMENTS: readonly string[] = Object.freeze(["Cellar", ".nvm", ".volta", ".asdf", ".fnm", ".nodenv", ".n"]);
const VERSIONED_OPT = /^node@\d+$/;

function escapeXml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}
function unescapeXml(value: string): string {
  return value.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, "&");
}

/** True when a node path names a version-specific install that the next upgrade deletes. */
export function nodePathVersioned(node: string): boolean {
  const segments = node.split("/");
  return segments.some((segment, i) => UNSTABLE_NODE_SEGMENTS.includes(segment) || (VERSIONED_OPT.test(segment) && segments[i - 1] !== "opt"));
}

/**
 * Render the observer LaunchAgent. It names no StandardOutPath or
 * StandardErrorPath, because launchd would append to them without bound.
 * The argument shape must match the `run-watch` dispatch in server/src/cli.ts.
 */
export function generateWatchAgentPlist(programArguments: readonly string[]): string {
  if (programArguments.length !== WATCH_PROGRAM_ARGUMENT_COUNT || programArguments[2] !== "castle-wall" || programArguments[3] !== "run-watch" ||
      programArguments[4] !== "--fortress" || programArguments[6] !== "--launch-agent") {
    throw new Error("Observer LaunchAgent arguments must identify run-watch.");
  }
  for (const argument of programArguments) if (CONTROL_TEXT.test(argument)) throw new Error("Control characters are not allowed in LaunchAgent values.");
  const node = programArguments[0]!;
  const cli = programArguments[1]!;
  const fortress = programArguments[5]!;
  if (!isAbsolute(node) || !isAbsolute(cli) || !isAbsolute(fortress)) throw new Error("Observer LaunchAgent paths must be absolute.");
  // A versioned or Cellar node path is refused so an upgrade can never strand the observer on a deleted interpreter.
  if (nodePathVersioned(node)) throw new Error("Observer LaunchAgent node path names a version-specific install.");
  const path = [...new Set([dirname(node), "/usr/bin", "/bin", "/usr/sbin", "/sbin"])].join(":");
  return `${PLIST_HEADER}
<dict>
\t<key>Label</key>
\t<string>${OBSERVER_LABEL}</string>
\t<key>ProgramArguments</key>
\t<array>
${programArguments.map(argument => `\t\t<string>${escapeXml(argument)}</string>`).join("\n")}
\t</array>
\t<key>RunAtLoad</key>
\t<true/>
\t<key>KeepAlive</key>
\t<dict>
\t\t<key>SuccessfulExit</key>
\t\t<false/>
\t</dict>
\t<key>ThrottleInterval</key>
\t<integer>${WATCH_THROTTLE_INTERVAL_S}</integer>
\t<key>LimitLoadToSessionType</key>
\t<string>Aqua</string>
\t<key>EnvironmentVariables</key>
\t<dict>
\t\t<key>PATH</key>
\t\t<string>${escapeXml(path)}</string>
\t</dict>
\t<key>WorkingDirectory</key>
\t<string>/</string>
</dict>
</plist>
`;
}

function plistProgramArguments(contents: string): string[] {
  const array = /<key>ProgramArguments<\/key>\s*<array>([\s\S]*?)<\/array>/.exec(contents)?.[1] ?? "";
  return [...array.matchAll(/<string>([\s\S]*?)<\/string>/g)].map(match => unescapeXml(match[1]!));
}

/** Accept exactly the generator's output for its own arguments; any added, removed or reordered key is refused. */
export function watchAgentLaunchAgentWellFormed(contents: string): boolean {
  try { return generateWatchAgentPlist(plistProgramArguments(contents)) === contents; }
  catch { return false; }
}

// ---------------------------------------------------------------------------
// System-domain launchctl print.
// ---------------------------------------------------------------------------
export interface SystemJobPrint {
  valid: boolean;
  pid: number | null;
  program: string | null;
  arguments: string[];
  username: string | null;
}
const INVALID_PRINT: SystemJobPrint = Object.freeze({ valid: false, pid: null, program: null, arguments: [], username: null }) as SystemJobPrint;
/** launchctl exits 113 for a label the domain does not hold (captured on macOS 26.6.2, operator account). */
export const LAUNCHCTL_SYSTEM_NOT_FOUND_STATUS = 113;

/**
 * Parse `launchctl print system/<label>`. It accepts the service fields with
 * or without the outer `system/<label> = {` wrapper, reads only service-level
 * `pid`, `program` and `username` fields and the service's own `arguments`
 * block, and ignores nested dictionaries. A duplicated field reads as unknown.
 * Field names follow the modelled and captured texts in
 * server/test/castle-wall/liveness/fixtures/launchctl-print.json.
 */
export function parseSystemJobPrint(stdout: string): SystemJobPrint {
  const lines = stdout.split("\n").filter(line => line.trim() !== "");
  if (lines.length === 0) return INVALID_PRINT;
  const wrapped = /^\S.*=\s*\{$/.test(lines[0]!);
  const serviceDepth = wrapped ? 1 : 0;
  const blocks: string[] = [];
  const fields = new Map<string, string[]>();
  const args: string[] = [];
  let argumentBlocks = 0;
  let state_CLOSED = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (state_CLOSED) return INVALID_PRINT;
    if (line === "}") {
      if (blocks.length === 0) return INVALID_PRINT;
      blocks.pop();
      if (wrapped && blocks.length === 0) state_CLOSED = true;
      continue;
    }
    if (blocks.length === serviceDepth + 1 && blocks[serviceDepth] === "arguments") { args.push(line); continue; }
    const opening = /^(.*?)\s*=\s*\{$/.exec(line);
    if (opening) {
      if (blocks.length === serviceDepth && opening[1] === "arguments") argumentBlocks++;
      blocks.push(opening[1]!);
      continue;
    }
    if (blocks.length === serviceDepth) {
      const field = /^([a-z][a-z ]*?)\s*=\s*(.*)$/.exec(line);
      if (field) fields.set(field[1]!, [...(fields.get(field[1]!) ?? []), field[2]!]);
    }
  }
  if (blocks.length !== 0 || (wrapped && !state_CLOSED)) return INVALID_PRINT;
  // A print that names no service field is not a job print, so unrecognized text never reads as an installed job.
  if (fields.size === 0) return INVALID_PRINT;
  const one = (name: string): string | null => { const values = fields.get(name); return values?.length === 1 ? values[0]! : null; };
  const pidText = one("pid");
  const pidValue = pidText !== null && /^\d+$/.test(pidText) ? Number(pidText) : Number.NaN;
  return {
    valid: true,
    pid: Number.isSafeInteger(pidValue) && pidValue > 0 ? pidValue : null,
    program: one("program"),
    arguments: argumentBlocks === 1 ? args : [],
    username: one("username"),
  };
}

/**
 * True only for the captured not-found outcome in `captured_system_not_found`
 * in server/test/castle-wall/liveness/fixtures/launchctl-print.json: exit 113,
 * no service block, and the `Could not find service "<label>"` line.
 * Any other result cannot prove the job absent.
 */
export function systemJobNotFound(result: { code: number | null; stdout: string; stderr: string }, label: string): boolean {
  const text = `${result.stdout}\n${result.stderr}`;
  return result.code === LAUNCHCTL_SYSTEM_NOT_FOUND_STATUS && !/^[^\n]*=\s*\{\s*$/m.test(result.stdout) &&
    text.split("\n").some(line => line.trim().startsWith(`Could not find service "${label}"`));
}
