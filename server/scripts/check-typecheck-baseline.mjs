import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";

const args = new Set(process.argv.slice(2));
const update = args.has("--update");
const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(scriptDir, "..");
const baselinePath = join(
  packageRoot,
  "test/fixtures/typecheck-tests-baseline.txt",
);
const normalizedPackageRoot = packageRoot.replaceAll("\\", "/");

const diagnosticLinePattern =
  /^(.+\.(?:ts|tsx|mts))\(\d+,\d+\): error TS\d+: .+$/;

function normalizeDiagnostics(output) {
  return output
    .split(/\r?\n/)
    .map((line) =>
      line
        .replaceAll("\\", "/")
        .replaceAll(normalizedPackageRoot, "<server>")
        .trimEnd(),
    )
    .filter((line) => diagnosticLinePattern.test(line))
    .sort();
}

function readBaseline() {
  if (!existsSync(baselinePath)) {
    return [];
  }

  return readFileSync(baselinePath, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trimEnd())
    .filter((line) => line.length > 0 && !line.startsWith("#"))
    .sort();
}

function writeBaseline(diagnostics) {
  mkdirSync(dirname(baselinePath), { recursive: true });
  const header = [
    "# Generated by `npm run typecheck:tests:update`.",
    "# These are the current known diagnostics for package-owned tests/scripts/configs.",
    "# `npm run typecheck` fails when this set changes without an intentional baseline update.",
    `# Count: ${diagnostics.length}`,
    "",
  ];
  writeFileSync(baselinePath, `${header.join("\n")}${diagnostics.join("\n")}\n`);
}

function diffDiagnostics(current, baseline) {
  const baselineSet = new Set(baseline);
  const currentSet = new Set(current);

  return {
    added: current.filter((line) => !baselineSet.has(line)),
    removed: baseline.filter((line) => !currentSet.has(line)),
  };
}

const result = spawnSync(
  "tsc",
  ["-p", "tsconfig.typecheck.json", "--pretty", "false"],
  {
    cwd: packageRoot,
    encoding: "utf8",
    env: { ...process.env, FORCE_COLOR: "0", NO_COLOR: "1" },
    maxBuffer: 200 * 1024 * 1024,
  },
);

if (result.error) {
  console.error(`Unable to run tsc for the tests/scripts baseline: ${result.error.message}`);
  process.exit(1);
}

const current = normalizeDiagnostics(`${result.stdout ?? ""}${result.stderr ?? ""}`);

if (update) {
  writeBaseline(current);
  console.log(`Updated typecheck diagnostic baseline (${current.length} diagnostics).`);
  process.exit(0);
}

const baseline = readBaseline();
if (baseline.length === 0 && current.length > 0) {
  console.error(
    "Missing tests/scripts typecheck baseline. Run `npm run typecheck:tests:update` intentionally.",
  );
  process.exit(1);
}

const { added, removed } = diffDiagnostics(current, baseline);
if (added.length > 0 || removed.length > 0) {
  console.error("Tests/scripts typecheck diagnostics changed.");
  console.error(`Current: ${current.length}; baseline: ${baseline.length}`);
  if (added.length > 0) {
    console.error(`\nNew diagnostics (${added.length}):`);
    for (const line of added.slice(0, 40)) {
      console.error(`+ ${line}`);
    }
  }
  if (removed.length > 0) {
    console.error(`\nResolved diagnostics (${removed.length}):`);
    for (const line of removed.slice(0, 40)) {
      console.error(`- ${line}`);
    }
  }
  console.error("\nIf the change is intentional, run `npm run typecheck:tests:update`.");
  process.exit(1);
}

console.log(`Tests/scripts typecheck baseline unchanged (${current.length} diagnostics).`);
