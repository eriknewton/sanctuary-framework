function hexToBytes(hex: string): Uint8Array {
  return Uint8Array.from(Buffer.from(hex, "hex"));
}

function sha256Hex(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

describe("ML-DSA-65 FIPS 204 KATs", () => {
  it("matches the NIST ACVP ML-DSA-65 keyGen vector", () => {
    const keypair = ml_dsa65.keygen(hexToBytes(KEYGEN_ACVP.seed));

    expect(keypair.publicKey).toHaveLength(ML_DSA_65_PUBLIC_KEY_BYTES);
    expect(keypair.secretKey).toHaveLength(ML_DSA_65_SECRET_KEY_BYTES);
    expect(sha256Hex(keypair.publicKey)).toBe(KEYGEN_ACVP.publicKeySha256);
    expect(sha256Hex(keypair.secretKey)).toBe(KEYGEN_ACVP.secretKeySha256);
  });

  it("matches the NIST ACVP ML-DSA-65 deterministic sigGen vector", () => {
    const secretKey = hexToBytes(SIGGEN_SK_HEX);
    const message = hexToBytes(SIGGEN_ACVP.message);
    const context = hexToBytes(SIGGEN_ACVP.context);

    expect(secretKey).toHaveLength(ML_DSA_65_SECRET_KEY_BYTES);
    expect(sha256Hex(secretKey)).toBe(SIGGEN_ACVP.secretKeySha256);

    const signature = ml_dsa65.sign(message, secretKey, {
      context,
      extraEntropy: false,
    });
    const publicKey = ml_dsa65.getPublicKey(secretKey);

    expect(signature).toHaveLength(ML_DSA_65_SIGNATURE_BYTES);
    expect(sha256Hex(signature)).toBe(SIGGEN_ACVP.signatureSha256);
    expect(ml_dsa65.verify(signature, message, publicKey, { context })).toBe(true);

    const tamperedMessage = Uint8Array.from(message);
    tamperedMessage[0] ^= 1;
    expect(ml_dsa65.verify(signature, tamperedMessage, publicKey, { context })).toBe(false);

    const tamperedPublicKey = Uint8Array.from(publicKey);
    tamperedPublicKey[0] ^= 1;
    expect(ml_dsa65.verify(signature, message, tamperedPublicKey, { context })).toBe(false);

    const tamperedSignature = Uint8Array.from(signature);
    tamperedSignature[0] ^= 1;
    expect(ml_dsa65.verify(tamperedSignature, message, publicKey, { context })).toBe(false);

    const truncatedSignature = signature.slice(0, signature.length - 1);
    expect(ml_dsa65.verify(truncatedSignature, message, publicKey, { context })).toBe(false);
  });
});
